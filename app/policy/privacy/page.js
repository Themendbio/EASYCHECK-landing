/* ── 프레젠테이션 헬퍼 ── */

function Article({ title, children }) {
    return (
        <section className="mt-10">
            <h2 className="text-[18px] lg:text-[20px] font-semibold text-text-primary mb-3">
                {title}
            </h2>
            {children}
        </section>
    );
}

function P({ children }) {
    return (
        <p
            className="text-[15px] text-text-secondary leading-[1.7] mb-3"
            style={{ wordBreak: 'keep-all' }}
        >
            {children}
        </p>
    );
}

function SubTitle({ children }) {
    return <h3 className="text-[15px] font-semibold text-text-primary mt-5 mb-2">{children}</h3>;
}

function Small({ children }) {
    return (
        <p
            className="text-[13px] text-text-tertiary leading-[1.6] mt-2"
            style={{ wordBreak: 'keep-all' }}
        >
            {children}
        </p>
    );
}

function NumList({ items, ordered = true }) {
    if (ordered) {
        return (
            <ol className="list-decimal pl-5 space-y-2 text-[15px] text-text-secondary leading-[1.7]">
                {items.map((it, i) => (
                    <li key={i} style={{ wordBreak: 'keep-all' }}>
                        {it}
                    </li>
                ))}
            </ol>
        );
    }
    return (
        <div className="space-y-2">
            {items.map((it, i) => (
                <p
                    key={i}
                    className="text-[15px] text-text-secondary leading-[1.7]"
                    style={{ wordBreak: 'keep-all' }}
                >
                    {it}
                </p>
            ))}
        </div>
    );
}

function BulletList({ items }) {
    return (
        <ul className="list-disc pl-5 space-y-1.5 text-[15px] text-text-secondary leading-[1.7]">
            {items.map((it, i) => (
                <li key={i} style={{ wordBreak: 'keep-all' }}>
                    {it}
                </li>
            ))}
        </ul>
    );
}

function Table({ head, rows }) {
    return (
        <div className="overflow-x-auto my-4">
            <table className="w-full border-collapse text-[14px]">
                <thead>
                    <tr className="bg-bg-subtle">
                        {head.map((h, i) => (
                            <th
                                key={i}
                                className="border border-border px-3 py-2 text-left font-semibold text-text-primary align-top"
                            >
                                {h}
                            </th>
                        ))}
                    </tr>
                </thead>
                <tbody>
                    {rows.map((row, r) => (
                        <tr key={r}>
                            {row.map((cell, c) => (
                                <td
                                    key={c}
                                    className="border border-border px-3 py-2 text-text-secondary align-top"
                                    style={{ wordBreak: 'keep-all' }}
                                >
                                    {cell}
                                </td>
                            ))}
                        </tr>
                    ))}
                </tbody>
            </table>
        </div>
    );
}

function Callout({ title, children }) {
    return (
        <div className="bg-bg-subtle border border-border rounded-lg px-5 py-4 my-6">
            <p className="text-[13px] font-semibold text-text-primary mb-1">[{title}]</p>
            <p
                className="text-[14px] text-text-secondary leading-[1.7] m-0"
                style={{ wordBreak: 'keep-all' }}
            >
                {children}
            </p>
        </div>
    );
}
